
"""热度口径 + 权重世代戳自检：不依赖 pytest，用临时库跑必验夹具。

    python3 scripts/口径校验.py

1. 同一纯送礼窗：等权口径主指标为 0（并给出零因），金额加权口径为 送礼×权重。
2. 改权重不回写已关窗；之后关闭的窗按新权重冻结。
3. 改公式与关窗（装载持锁）并发：改口径失败闭，站规与已关窗都不半截。
4. 权重世代戳（入窗戳冻结发射）：
   - 甲：只投送礼累进 → 改站规权重 → 再发射，主指标锁在戳内值，不按新权重重算；
   - 乙：无戳（戳被抹掉）时发射/迟到失败闭，整票回滚，不出现「累计已加、戳空」；
   - 戳内累计与窗行分叉时拒绝关闭；
   - 改权重与关窗抢锁：改口径失败闭，窗行不出现半截混用公式版本；
   - 只读核证接口与累计写闸/发射写闸/迟到写/热度页结果一致。
"""
import json
import os
import sys
import tempfile
import threading
import time
from pathlib import Path

根 = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(根 / "backend"))
夹具 = 根 / "fixtures"

失败 = []


def 断言(条件, 说明):
    print(("  ok  " if 条件 else "  FAIL") + "  " + 说明)
    if not 条件:
        失败.append(说明)


def 新环境(公式="金额加权", 权重=2):
    """独立临时库 + 重新导入 app 模块（db.py 在 import 时读取数据目录）。"""
    目录 = tempfile.mkdtemp(prefix="播浪-口径-")
    os.environ["数据目录"] = 目录
    os.environ["夹具目录"] = str(夹具)
    for 名 in list(sys.modules):
        if 名 == "app" or 名.startswith("app."):
            del sys.modules[名]
    from app import seed
    from app.db import 连接
    from app.services import 口径, 装载, 贯验
    from app.modules import 权重世代戳 as 权

    seed.初始化库()
    if 公式 != "金额加权" or 权重 != 2:
        口径.改口径({"公式": 公式, "权重": 权重})
    return {"口径": 口径, "装载": 装载, "贯验": 贯验, "连接": 连接, "权": 权}


def 推(M, 批次, 事件):
    return M["装载"].装一批({"批次编号": 批次, "事件": 事件})


def 装(M, 名):
    return M["装载"].装一批(json.loads((夹具 / f"{名}.json").read_text(encoding="utf-8")))


def 窗(M):
    c = M["连接"]()
    try:
        return {
            r["窗键"]: dict(r)
            for r in c.execute("SELECT * FROM 热度窗 ORDER BY 窗起事件时")
        }
    finally:
        c.close()


def 只送礼窗键(M):
    c = M["连接"]()
    try:
        r = c.execute(
            "SELECT 窗键 FROM 热度窗 WHERE 点赞合计=0 AND 送礼合计>0 ORDER BY 窗起事件时 LIMIT 1"
        ).fetchone()
        return r["窗键"] if r else None
    finally:
        c.close()


print("== 1. 同窗一笔纯送礼：甲 0，乙 加权值 ==")
甲 = 新环境("等权计数", 2)
装(甲, "纯送礼样例")
w甲 = 窗(甲)[只送礼窗键(甲)]
断言(w甲["主指标"] == 0 and w甲["主指标公式"] == "等权计数", "等权口径主指标=0")
断言(
    甲["口径"].装饰窗(甲["连接"]().execute(
        "SELECT * FROM 热度窗 WHERE 窗键=?", (w甲["窗键"],)
    ).fetchone(), 甲["口径"].读当前(甲["连接"]()))["主指标零因"]
    == "等权口径不计送礼（纯送礼窗）",
    "等权口径 0 值有零因，可与空窗区分",
)
乙 = 新环境("金额加权", 2)
装(乙, "纯送礼样例")
w乙 = 窗(乙)[只送礼窗键(乙)]
断言(w乙["主指标"] == w乙["送礼合计"] * 2, f"金额加权主指标={w乙['送礼合计']}×2={w乙['主指标']}")

print("== 2. 改权重不撬已关窗 ==")
M = 新环境("金额加权", 2)
装(M, "纯送礼样例")
前 = 窗(M)[只送礼窗键(M)]
M["口径"].改口径({"权重": 5})
后 = 窗(M)[只送礼窗键(M)]
断言(前["主指标"] == 后["主指标"] and 后["主指标权重"] == 2, "改权重 2→5 后已关窗主指标与冻结权重不变")
断言(M["贯验"].跑贯验()["是否通过"], "互证按冻结口径通过")

print("== 3. 改公式与关窗并发：失败闭 ==")
M = 新环境("金额加权", 2)
装(M, "纯送礼样例")
前版本 = M["口径"].读当前(M["连接"]())["口径版本"]
前窗 = 窗(M)
结果 = {}


def 改():
    time.sleep(0.05)
    try:
        结果["r"] = M["口径"].改口径({"公式": "等权计数", "权重": 2})
    except M["口径"].并发冲突 as e:
        结果["e"] = str(e)


M["口径"].锁.acquire()  
t = threading.Thread(target=改)
t.start()
time.sleep(0.3)
M["口径"].锁.release()
t.join()
断言("e" in 结果 and "r" not in 结果, f"并发改口径被拒: {结果.get('e')}")
当前 = M["口径"].读当前(M["连接"]())
断言(当前["公式"] == "金额加权" and 当前["口径版本"] == 前版本, "站规未被半截改写")
断言(窗(M) == 前窗, "已关窗发射结果未变")
断言(not M["口径"].读变更(M["连接"]()), "失败变更未留记录")

print("== 4. 甲：送礼累进 → 改权重 → 再发射，主指标锁在戳内值 ==")
M = 新环境("金额加权", 2)
推(M, "甲-1", [
    {"事件编号": "甲E1", "房间键": "房A", "事件类型": "送礼",
     "事件时": "2026-11-22T12:00:10Z", "处理时": "t1", "送礼额": 50},
])
w0 = 窗(M)[只送礼窗键(M)]
断言(w0["状态"] == "开启" and w0["主指标"] == 100 and w0["主指标权重"] == 2,
     f"累进时按当时权重 2：主指标={w0['主指标']}")
c = M["连接"]()
try:
    戳数 = c.execute("SELECT COUNT(*) FROM 权重世代戳 WHERE 窗键=?", (w0["窗键"],)).fetchone()[0]
finally:
    c.close()
断言(戳数 == 1, f"加权入窗成功即打戳，戳数={戳数}（禁止戳空）")

M["口径"].改口径({"权重": 5})
推(M, "甲-2", [
    {"事件编号": "甲E2", "房间键": "房A", "事件类型": "点赞",
     "事件时": "2026-11-22T12:01:10Z", "处理时": "t2", "点赞增量": 0},
])
w1 = 窗(M)[w0["窗键"]]
断言(w1["状态"] == "已关闭" and w1["主指标"] == 100,
     f"发射主指标锁在戳内累计 100，不按新权重 5 重算（否则 250）：{w1['主指标']}")
断言(w1["主指标权重"] == 2, f"发射冻结的权重来自戳=2，不混用现行权重 5：{w1['主指标权重']}")
r = M["贯验"].跑贯验()
断言(r["是否通过"], f"互证按逐笔世代累进通过：{r['问题']}")

print("== 5. 乙：缺戳时发射/迟到失败闭，整票回滚 ==")
M = 新环境("金额加权", 2)
装(M, "准时热度样例")
c = M["连接"]()
try:
    c.execute("DELETE FROM 权重世代戳")
    c.commit()
finally:
    c.close()
事件前 = len(
    (lambda c: [dict(r) for r in c.execute("SELECT * FROM 互动事件")])(M["连接"]())
)
失败闭 = False
try:
    装(M, "迟到修正样例")
except M["权"].戳异常 as e:
    失败闭 = "戳" in str(e)
断言(失败闭, "无戳时迟到修正失败闭，不按现行权重硬算")
c = M["连接"]()
try:
    事件后 = c.execute("SELECT COUNT(*) FROM 互动事件").fetchone()[0]
    撤回 = c.execute("SELECT COUNT(*) FROM 撤回单").fetchone()[0]
finally:
    c.close()
断言(事件后 == 事件前 and 撤回 == 0, "失败闭时整票回滚：无新事件、无撤回单")

M = 新环境("金额加权", 2)
推(M, "乙-1", [
    {"事件编号": "乙E1", "房间键": "房A", "事件类型": "送礼",
     "事件时": "2026-11-22T12:00:10Z", "处理时": "t1", "送礼额": 50},
])
c = M["连接"]()
try:
    c.execute("DELETE FROM 权重世代戳")
    c.commit()
finally:
    c.close()
失败闭 = False
try:
    推(M, "乙-2", [
        {"事件编号": "乙E2", "房间键": "房A", "事件类型": "点赞",
         "事件时": "2026-11-22T12:01:10Z", "处理时": "t2", "点赞增量": 1},
    ])
except M["权"].戳异常 as e:
    失败闭 = "戳" in str(e)
断言(失败闭, "无戳时关窗发射失败闭，不按现行权重回溯")
w = 窗(M)[只送礼窗键(M)]
断言(w["状态"] == "开启" and w["主指标"] == 100, "失败闭后窗未被半截关闭、累计未变")

print("== 6. 戳内累计与窗行分叉 → 拒绝关闭 ==")
M = 新环境("金额加权", 2)
推(M, "叉-1", [
    {"事件编号": "叉E1", "房间键": "房A", "事件类型": "送礼",
     "事件时": "2026-11-22T12:00:10Z", "处理时": "t1", "送礼额": 50},
])
c = M["连接"]()
try:
    c.execute("UPDATE 权重世代戳 SET 累计主指标=9999")
    c.commit()
finally:
    c.close()
失败闭 = False
try:
    推(M, "叉-2", [
        {"事件编号": "叉E2", "房间键": "房A", "事件类型": "点赞",
         "事件时": "2026-11-22T12:01:10Z", "处理时": "t2", "点赞增量": 1},
    ])
except M["权"].戳异常:
    失败闭 = True
断言(失败闭, "戳内主指标与窗行分叉时拒绝关闭发射")
w = 窗(M)[只送礼窗键(M)]
断言(w["状态"] == "开启", "分叉时窗保持开启，不半截发射")
c = M["连接"]()
try:
    核证叉 = M["权"].查权重戳(c)
finally:
    c.close()
断言(not 核证叉["钉死"] and not 核证叉["一致性"][0]["一致"],
     "只读核证对分叉的窗报不一致（钉死=False）")

print("== 7. 改权重与关窗抢锁：不得半截混用公式版本 ==")
M = 新环境("金额加权", 2)
推(M, "抢-1", [
    {"事件编号": "抢E1", "房间键": "房A", "事件类型": "送礼",
     "事件时": "2026-11-22T12:00:10Z", "处理时": "t1", "送礼额": 50},
])
抢锁结果 = {}


def 装载关窗():
    time.sleep(0.05)
    try:
        抢锁结果["装"] = 推(M, "抢-2", [
            {"事件编号": "抢E2", "房间键": "房A", "事件类型": "点赞",
             "事件时": "2026-11-22T12:01:10Z", "处理时": "t2", "点赞增量": 1},
        ])
    except Exception as e:  # noqa: BLE001
        抢锁结果["装错"] = str(e)


def 改权重():
    time.sleep(0.1)
    try:
        抢锁结果["改"] = M["口径"].改口径({"权重": 9})
    except M["口径"].并发冲突 as e:
        抢锁结果["改错"] = str(e)


M["口径"].锁.acquire()  # 模拟装载持锁
t1 = threading.Thread(target=装载关窗)
t2 = threading.Thread(target=改权重)
t1.start()
t2.start()
time.sleep(0.3)
M["口径"].锁.release()
t1.join()
t2.join()
w = 窗(M)[只送礼窗键(M)]
断言(w["主指标"] == 100 and w["主指标权重"] == 2,
     f"抢锁后窗行主指标/权重同世代，不半截混用：{w['主指标']}/{w['主指标权重']}")
断言("改错" in 抢锁结果, f"并发改权重失败闭：{抢锁结果.get('改错')}")
断言(M["口径"].读当前(M["连接"]())["权重"] == 2, "站规权重未被半截改写")
r = M["贯验"].跑贯验()
断言(r["是否通过"], f"抢锁后互证通过：{r['问题']}")

print("== 8. 只读核证接口与写闸/互证协同 ==")
M = 新环境("金额加权", 2)
推(M, "证-1", [
    {"事件编号": "证E1", "房间键": "房A", "事件类型": "送礼",
     "事件时": "2026-11-22T12:00:10Z", "处理时": "t1", "送礼额": 50},
])
c = M["连接"]()
try:
    核证 = M["权"].查权重戳(c)
finally:
    c.close()
断言(核证["钉死"] and not 核证["采信现行权重"], "核证显示钉死、不采信现行权重")
断言(not 核证["缺戳窗"], "核证无缺戳窗")
断言(核证["一致性"] and all(项["一致"] for 项 in 核证["一致性"]), "戳内累计与窗行一致")
断言(核证["戳数"] == 1 and 核证["钉死窗数"] == 1, "戳数与钉死窗数一致")

print()
if 失败:
    print(f"失败 {len(失败)} 项")
    sys.exit(1)
print("全部通过")
