def 查权重戳(conn, 窗键: str | None = None) -> dict:
    """只读核证：返回权重世代戳、钉死状态与一致性，不写任何数据。

    - `钉死`：所有已累计的热度窗都持有一枚合法戳，且戳内累计 = 窗行主指标。
    - `采信现行权重`：本设计取舍为「入窗戳冻结发射」，恒为 False；
      已累计的结果只认戳，现行权重只影响尚未累计的新窗。
    - `缺戳窗`：已累计却没有戳的窗（禁止发射/修正的数据缺陷，需修数）。
    """
    if 窗键:
        窗集 = conn.execute(
            "SELECT * FROM 热度窗 WHERE 窗键=?", (窗键,)
        ).fetchall()
        rows = [
            dict(r)
            for r in conn.execute(
                "SELECT * FROM 权重世代戳 WHERE 窗键=? ORDER BY 编号 DESC",
                (窗键,),
            )
        ]
    else:
        窗集 = conn.execute(
            "SELECT * FROM 热度窗 WHERE 事件笔数>0 ORDER BY 窗起事件时"
        ).fetchall()
        rows = [
            dict(r)
            for r in conn.execute(
                "SELECT * FROM 权重世代戳 ORDER BY 编号 DESC LIMIT 200"
            )
        ]
    总数 = conn.execute("SELECT COUNT(*) FROM 权重世代戳").fetchone()[0]
    钉死窗数 = conn.execute(
        "SELECT COUNT(DISTINCT 窗键) FROM 权重世代戳"
    ).fetchone()[0]

    一致性 = []
    缺戳窗 = []
    for 窗 in 窗集:
        键 = 窗["窗键"]
        最新 = 最新戳(conn, 键)
        if not 最新:
            缺戳窗.append(
                {
                    "窗键": 键,
                    "状态": 窗["状态"],
                    "窗行主指标": int(窗["主指标"] or 0),
                    "原因": "已累计但权重世代戳为空",
                }
            )
            continue
        try:
            公式, 权重, 版本 = 戳世代(最新)
            一致 = bool(
                int(最新["累计主指标"]) == int(窗["主指标"] or 0)
                and (窗["主指标公式"] or "").strip() == 公式
                and int(窗["主指标权重"] or 0) == 权重
                and int(窗["口径版本"] or 0) == 版本
                and (最新["戳号"] or "").strip()
            )
            错误 = "" if 一致 else "戳内累计/世代与窗行不一致"
        except 戳异常 as e:
            公式 = 最新.get("公式版本", "")
            权重 = 最新.get("权重值", "")
            版本 = 窗["口径版本"]
            一致 = False
            错误 = str(e)
        一致性.append(
            {
                "窗键": 键,
                "状态": 窗["状态"],
                "窗行主指标": int(窗["主指标"] or 0),
                "戳内累计": int(最新["累计主指标"]),
                "公式": 公式,
                "权重": 权重,
                "口径版本": 版本,
                "公式版本": 最新["公式版本"],
                "戳号": 最新["戳号"],
                "一致": 一致,
                "错误": 错误,
            }
        )

    钉死 = not 缺戳窗 and all(项["一致"] for 项 in 一致性)
    return {
        "权重戳": rows,
        "钉死": bool(钉死),
        "采信现行权重": False,
        "戳数": int(总数),
        "钉死窗数": int(钉死窗数),
        "已累计窗数": len(窗集),
        "缺戳窗": 缺戳窗,
        "一致性": 一致性,
        "设计取舍": "入窗戳冻结发射；发射主指标只认戳内累计，现行权重不得回溯",
    }
